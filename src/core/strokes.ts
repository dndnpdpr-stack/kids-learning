// 손으로 작성한 체크포인트. 좌표는 0~1, 원점은 왼쪽 위, y는 아래로 증가.
// 글자는 대략 0.15~0.85 안에 둔다. 획당 3~8개, 인접 점은 0.1 이상 떨어뜨린다.

const r = (n: number) => Math.round(n * 1000) / 1000;
/** 위쪽에서 시작해 반시계 방향(왼쪽으로)으로 도는 타원 체크포인트 */
function ellipse(cx: number, cy: number, rx: number, ry: number, n = 8): Pt[] {
  return Array.from({ length: n }, (_, i) => {
    const t = (2 * Math.PI * i) / n;
    return { x: r(cx - rx * Math.sin(t)), y: r(cy - ry * Math.cos(t)) };
  });
}
